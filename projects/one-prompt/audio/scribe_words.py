"""Subtitle word timings from ElevenLabs Scribe transcripts of the narration.

  python3 audio/scribe_words.py <transcripts dir> <vo dir> <say.json> > src/vo_words.js

<transcripts dir>/<line>.json holds {"words": [{"text", "start", "end"}, ...]} for <vo dir>/<line>.mp3 (Scribe's words.json).
<say.json> maps line id -> subtitle text (node audio/say.mjs). Each subtitle word gets the start of the spoken word it matches,
measured from the line's speech onset (vo.json lead); a dash gets the end of the word before it. Differences between the
subtitle text and what was said are reported on stderr.
"""
import json, re, sys, difflib, os
import numpy as np
sys.path.insert(0, os.path.dirname(__file__))
from score import decode, SR


def silences(x, thr=-40, min_len=0.06):
    """(start, end) of stretches quieter than thr dB (10 ms RMS) lasting at least min_len seconds"""
    w = int(SR * 0.01); n = len(x) // w
    q = 20 * np.log10(np.sqrt(np.mean(x[: n * w].reshape(n, w) ** 2, axis=1)) + 1e-9) < thr
    out, i = [], 0
    while i < n:
        if q[i]:
            j = i
            while j < n and q[j]: j += 1
            if (j - i) * 0.01 >= min_len: out.append((i * 0.01, j * 0.01))
            i = j
        else: i += 1
    return out

tdir, vdir, sayp = sys.argv[1:4]
meta, say = json.load(open(f'{vdir}/vo.json')), json.load(open(sayp))
norm = lambda w: re.sub(r"[^a-z0-9]", '', w.lower().replace('’', "'"))
out, bad = {}, 0
for lid, text in say.items():
    sp = [w for w in json.load(open(f'{tdir}/{lid}.json'))['words'] if w.get('type', 'word') == 'word' and not re.fullmatch(r'\[.*\]', w['text'])]
    sw = [w for w in sp if w['text'] != '—']
    # a word that follows a pause starts when the voice comes back, not a little before
    for sl in silences(decode(f'{vdir}/{lid}.mp3')):
        for w in sw:
            if sl[0] <= w['start'] + 0.03 and w['start'] - 0.05 < sl[1] <= w['start'] + 0.18:
                w['start'] = round(sl[1], 3)
    toks = text.split()
    a, b = [norm(t) for t in toks if t != '—'], [norm(w['text']) for w in sw]
    idx = [i for i, t in enumerate(toks) if t != '—']
    m = difflib.SequenceMatcher(a=a, b=b, autojunk=False)
    st = [None] * len(toks)
    for tag, i1, i2, j1, j2 in m.get_opcodes():
        if tag != 'equal':
            bad += 1
            print(f'{lid}: subtitle {" ".join(toks[idx[i] ] for i in range(i1, i2))!r} vs spoken {" ".join(w["text"] for w in sw[j1:j2])!r}', file=sys.stderr)
        for k in range(i2 - i1):
            j = j1 + min(k, max(0, j2 - j1 - 1)) if j2 > j1 else None
            if j is not None:
                st[idx[i1 + k]] = sw[j]['start']
    lead = meta[lid]['lead']
    for i, t in enumerate(toks):          # dashes: end of the previous word; unmatched words: interpolate
        if t == '—':
            prev = next((w for w in reversed(sw) if st[i - 1] is not None and w['start'] <= st[i - 1] + 1e-6), None) if i else None
            st[i] = prev['end'] if prev else (st[i - 1] or 0)
    for i in range(len(st)):
        if st[i] is None:
            lo = max([j for j in range(i) if st[j] is not None], default=None); hi = min([j for j in range(i + 1, len(st)) if st[j] is not None], default=None)
            st[i] = st[lo] + (st[hi] - st[lo]) * (i - lo) / (hi - lo) if lo is not None and hi is not None else (st[lo] + 0.2 if lo is not None else 0.0)
    out[lid] = [round(max(0.0, s - lead), 3) for s in st]
print('// generated by audio/scribe_words.py from ElevenLabs Scribe transcripts: start of each subtitle word, seconds after the line begins')
print('export const WORDS = ' + json.dumps(out, separators=(',', ':')) + ';')
print(f'{bad} differences', file=sys.stderr)
